export function isManufacturerId(value: string): value is ManufacturerId {
  return MANUFACTURERS.some((maker) => maker.id === value);
}

export function manufacturerById(id: ManufacturerId) {
  const maker = MANUFACTURERS.find((item) => item.id === id);
  if (!maker) throw new Error(`Unknown manufacturer ${id}`);
  return maker;
}

function slugPart(value: string): string {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/['.]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Slug shape: manufacturer-series-model. */
export function catalogSlug(input: {
  manufacturer: ManufacturerId;
  series: string;
  model: string;
  modelNumber?: string;
}): string {
  const series = slugPart(input.series);
  const model = slugPart(input.model);
  const modelPart = model.startsWith(`${series}-`)
    ? model.slice(series.length + 1)
    : model;
  let slug = `${input.manufacturer}-${series}-${modelPart}`;
  const number = input.modelNumber ? slugPart(input.modelNumber) : "";
  if (number && !slug.endsWith(`-${number}`) && !slug.endsWith(number)) {
    slug = `${slug}-${number}`;
  }
  return slug;
}

export function formatDimensions(
  widthFeet: number,
  widthInches: number,
  lengthFeet: number,
  lengthInches: number,
): string {
  const side = (feet: number, inches: number) =>
    inches > 0 ? `${feet}' ${inches}"` : `${feet}'`;
  return `${side(widthFeet, widthInches)} x ${side(lengthFeet, lengthInches)}`;
}

export function formatSqft(sqft: number): string {
  return `${new Intl.NumberFormat("en-US").format(sqft)} sq ft`;
}

export function formatBaths(baths: number): string {
  return Number.isInteger(baths) ? String(baths) : String(baths);
}

export function planDimensions(plan: CatalogPlan): string | null {
  const { widthFeet, widthInches, lengthFeet, lengthInches } = plan;
  if (
    widthFeet == null ||
    widthInches == null ||
    lengthFeet == null ||
    lengthInches == null
  ) {
    return null;
  }
  return formatDimensions(widthFeet, widthInches, lengthFeet, lengthInches);
}

export function planFactLine(plan: CatalogPlan): string {
  const facts = [
    `${plan.beds} beds`,
    `${formatBaths(plan.baths)} baths`,
    formatSqft(plan.sqft),
  ];
  const dimensions = planDimensions(plan);
  if (dimensions) facts.push(dimensions);
  return facts.join(" | ");
}

export function definePlan(input: CatalogPlanInput): CatalogPlan {
  const slug = catalogSlug({
    manufacturer: input.manufacturer,
    series: input.series,
    model: input.model,
    modelNumber: input.modelNumber,
  });
  const media = catalogMedia[slug];
  return {
    ...input,
    slug,
    price: null,
    photos: media?.photo ? [media.photo] : [],
    floorPlanImage: media?.floorPlan ?? null,
    features: input.features ?? [],
  };
}

